def d_tezad(b, ctx):
    out, seen = [], set()
    tok_of = {}
    for w in b.tokens:
        tok_of.setdefault(w, w)
        tok_of.setdefault(stem(w), w)
    for k in list(tok_of):
        for opp in ANT.get(k, ()):
            if opp in tok_of:
                a, c = tok_of[k], tok_of[opp]
                key = tuple(sorted((a, c)))
                if a != c and key not in seen:
                    seen.add(key)
                    in_one = (a in b.t1 and c in b.t1) or (a in b.t2 and c in b.t2)
                    out.append(mk(b, mesra_of(b, a, c) if (a in b.tokens and c in b.tokens) else M12,
                                  'تضاد', '', f'{a} … {c}',
                                  f'«{a}» و «{c}» متضادند.',
                                  'قوی' if in_one else 'متوسط'))
    for mnum, toks in ((M1, b.t1), (M2, b.t2)):
        for s1, s2 in PARADOX:
            h1 = next((t for t in toks if t in s1), '')
            h2 = next((t for t in toks if t in s2), '')
            if h1 and h2:
                out.append(mk(b, mnum, 'تناقض', 'پارادوکس احتمالی', f'{h1} … {h2}',
                              f'«{h1}» و «{h2}» ظاهراً جمع نمی‌شوند.',
                              'ضعیف', True, 'ممکن است تضاد ساده باشد.'))
    return out


def d_moraat(b, ctx):
    out = []
    uniq = list(dict.fromkeys(b.tokens))
    for name, fam in FAMILIES.items():
        hits = [w for w in uniq if w in fam]
        if len(hits) >= 2:
            in_both = (any(w in b.t1 for w in hits) and any(w in b.t2 for w in hits))
            if len(hits) >= 3:
                conf = 'قوی' if len(hits) >= 4 else 'متوسط'
                out.append(mk(b, M12 if in_both else mesra_of(b, *hits),
                              'مراعات نظیر', '', ' … '.join(hits),
                              f'واژه‌های هم‌خانواده در حوزهٔ «{name}».', conf))
            # دو واژهٔ هم‌حوزه به‌تنهایی تضمینی برای مراعات نظیر نیست؛
            # چون هر دو مصراع را در بر می‌گیرند هم اعلام نمی‌شود.
    return out


