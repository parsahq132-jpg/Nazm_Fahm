def _load_set(name):
    path = _RES_DIR / name
    if not path.exists():
        return set()
    items = set()
    with open(path, encoding='utf-8') as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith('#'):
                continue
            for w in WORD_RE.findall(normalize(line)):
                if 2 <= len(w) <= 20:
                    items.add(w)
    return items


def _load_pairs(name):
    path = _RES_DIR / name
    if not path.exists():
        return []
    pairs = []
    with open(path, encoding='utf-8') as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith('#'):
                continue
            parts = normalize(line).split()
            if len(parts) == 2:
                pairs.append((parts[0], parts[1]))
    return pairs


def _load_triples(name):
    path = _RES_DIR / name
    if not path.exists():
        return []
    triples = []
    with open(path, encoding='utf-8') as f:
        for line in f:
            line = line.rstrip('\n')
            if not line.strip() or line.startswith('#'):
                continue
            parts = line.split('\t')
            if len(parts) < 2:
                continue
            term = normalize(parts[0].strip())
            note = parts[1].strip() if len(parts) > 1 else ''
            partners = set()
            if len(parts) > 2 and parts[2].strip():
                partners = set(normalize(parts[2]).split())
            triples.append((term, note, partners if partners else None))
    return triples


def _load_idioms(name):
    path = _RES_DIR / name
    if not path.exists():
        return []
    items = []
    with open(path, encoding='utf-8') as f:
        for line in f:
            line = line.rstrip('\n')
            if not line.strip() or line.startswith('#'):
                continue
            if '\t' not in line:
                continue
            pat, meaning = line.split('\t', 1)
            pat, meaning = pat.strip(), meaning.strip()
            if not pat:
                continue
            try:
                re.compile(pat)
            except re.error:
                continue
            items.append((pat, meaning))
    return items


def _load_homon(name):
    path = _RES_DIR / name
    if not path.exists():
        return {}
    items = {}
    with open(path, encoding='utf-8') as f:
        for line in f:
            line = line.rstrip('\n')
            if not line.strip() or line.startswith('#'):
                continue
            if '\t' not in line:
                continue
            word, rest = line.split('\t', 1)
            word = normalize(word.strip())
            meanings = []
            for m in rest.split('|'):
                if ':' not in m:
                    continue
                label, words_str = m.split(':', 1)
                words = set(normalize(words_str).split())
                if label.strip() and words:
                    meanings.append((label.strip(), words))
            if word and meanings:
                items[word] = meanings
    return items


