def find_radif(ends):
    n = len(ends)
    if n < 4:
        return ()
    best = ()
    for k in range(1, 5):
        cnt = Counter(tuple(t[-k:]) for t in ends if len(t) > k)
        if not cnt:
            break
        suf, c = cnt.most_common(1)[0]
        if c >= max(3, 0.8 * n):
            best = suf
        else:
            break
    return best


def rhyme_word(tokens, rad):
    if not tokens:
        return ''
    k = len(rad)
    if k and len(tokens) > k and tuple(tokens[-k:]) == rad:
        return tokens[-k - 1]
    return tokens[-1]


def group_share(words):
    words = [w for w in words if w]
    if not words:
        return 0.0
    return Counter(rkey(w) for w in words).most_common(1)[0][1] / len(words)


def classify_form(beits, q1, q2, rad):
    n = len(beits)
    why = []
    if n == 0:
        return 'نامشخص', why
    inner = [ends_rhyme(a, c) for a, c in zip(q1, q2) if a and c]
    inner_ratio = sum(inner) / len(inner) if inner else 0.0
    share = group_share(q2)
    if n == 1:
        return 'تک‌بیت', ['فقط یک بیت داده شده است.']
    if n == 2 and all(b.t1 and b.t2 for b in beits):
        w1, w2, w3, w4 = q1[0], q2[0], q1[1], q2[1]
        if ends_rhyme(w1, w2) and ends_rhyme(w2, w4):
            return 'رباعی', ['چهار مصراع؛ مصراع‌های ۱، ۲ و ۴ هم‌قافیه‌اند.']
        if ends_rhyme(w1, w2) and ends_rhyme(w3, w4):
            return 'دوبیتی', ['هر بیت در درون خود هم‌قافیه است.']
        return 'قطعه / نامشخص', ['قافیه‌ها الگوی رباعی یا دوبیتی را کامل نمی‌کنند.']
    if inner_ratio >= 0.7 and share < 0.6:
        return 'مثنوی', [f'{fa(round(inner_ratio * 100))}٪ بیت‌ها در درون هم‌قافیه‌اند.']
    if share >= 0.6:
        tasri = bool(inner and inner[0])
        why.append(f'قافیهٔ مصراع‌های دوم یکسان است ({fa(round(share * 100))}٪).')
        if rad:
            why.append(f'ردیف مشترک: «{" ".join(rad)}».')
        if tasri:
            why.append('بیت نخست مصرّع (تصریع) است.')
        if tasri or rad or n >= 5:
            why.append('غزل و قصیده بیشتر با شمار ابیات و موضوع تفکیک می‌شوند.')
            return ('غزل' if n <= 15 else 'قصیده'), why
        return 'قطعه', why
    return 'نامشخص', ['الگوی قافیهٔ ثابتی دیده نشد.']


def rhyme_findings(beits, rad, q1, q2, core):
    out = []
    for k, b in enumerate(beits):
        if q2[k]:
            out.append(Finding(b.i, M2, 'قافیه', '', q2[k], f'واژهٔ قافیه: «{q2[k]}»', 'قوی'))
    if beits and rad:
        b = beits[0]
        out.append(Finding(b.i, M2, 'ردیف', '', ' '.join(rad),
                           f'«{" ".join(rad)}» در پایان مصراع‌های دوم تکرار شده است.', 'قوی'))
    if beits and core:
        grp_key = Counter(rkey(w) for w in q2 if w).most_common(1)
        if grp_key:
            same = [w for w in q2 if w and rkey(w) == grp_key[0][0]]
            if len(same) >= 2:
                b0 = beits[0]
                ev = q2[0] if q2[0] and rkey(q2[0]) == grp_key[0][0] else same[0]
                out.append(Finding(b0.i, M2, 'روی', '', ev,
                                   f'بخش مشترک قافیه‌ها: «{core}»؛ حرف روی (احتمالی): «{core[-1]}».',
                                   'متوسط'))
    if beits and beits[0].t1 and beits[0].t2 and ends_rhyme(q1[0], q2[0]):
        b = beits[0]
        out.append(Finding(b.i, M12, 'تصریع', '', f'{q1[0]} … {q2[0]}',
                           'دو مصراع بیت نخست هم‌قافیه‌اند (مطلع مصرّع).', 'قوی'))
    return out


def apply_filter(f, beit):
    frags = f.evidence.split(' … ')
    f.q1 = all((fr in beit.c1) or (fr in beit.c2) or (fr in (beit.c1 + ' | ' + beit.c2))
               or fr in ' '.join(frags)
               for fr in frags if fr) and bool(f.evidence)
    if f.device in ('تصریع',):
        f.q1 = True
    f.q2 = f.ok_def
    f.q3 = not f.alt
    if not f.q1:
        f.status, f.reason = 'رد', 'شاهد دقیق در متن پیدا نشد.'
    elif not f.q2:
        f.status, f.reason = 'رد', f.bad_def_reason or 'تعریف با شاهد تطبیق ندارد.'
    elif not f.q3:
        f.status, f.reason = 'با احتیاط', f.alt
    elif f.conf == 'ضعیف':
        f.status, f.reason = 'با احتیاط', 'شواهد ضعیف است.'
    else:
        f.status, f.reason = 'تأیید', 'شاهد دقیق دارد.'
    if (f.status == 'تأیید' and len(f.evidence.split()) <= 1
            and f.device not in ('قافیه', 'روی', 'تلمیح')):
        # تلمیح خودش با «دو نشانهٔ مستقل» سنجیده می‌شود؛ شاهد یک‌واژه‌ای بودن عیب نیست.
        f.status = 'با احتیاط'
        f.reason = 'شاهد تک‌واژه‌ای است.'


def analyze(text, progress=None):
    """تحلیل متن. progress(درصد, پیام) برای نمایش وضعیت است."""
    def tick(p, m):
        if progress:
            progress(p, m)

    tick(5, 'قطعه‌بندی ابیات…')
    beits = parse_poem(text)
    ends2 = [b.t2 for b in beits if b.t2]
    rad = find_radif(ends2)
    q1 = [rhyme_word(b.t1, rad) for b in beits]
    q2 = [rhyme_word(b.t2, rad) for b in beits]
    ctx = {'radif': set(rad)}

    qwords = [w for w in q2 if w]
    grp = Counter(rkey(w) for w in qwords).most_common(1)
    core = ''
    if grp:
        same = [w for w in qwords if rkey(w) == grp[0][0]]
        core = common_suffix(same) if len(same) >= 2 else ''

    form, reasons = classify_form(beits, q1, q2, rad)

    syl = [[sum(syl_count(t) for t in b.t1), sum(syl_count(t) for t in b.t2)] for b in beits]
    flat = [s for pair in syl for s in pair if s]
    if flat:
        mode = Counter(flat).most_common(1)[0][0]
        near = sum(1 for s in flat if abs(s - mode) <= 1) / len(flat)
        weight = (f'هجای تقریبی هر مصراع حدود {fa(mode)} است و {fa(round(near * 100))}٪ مصراع‌ها در بازهٔ ±۱ آن‌اند → '
                  + ('به‌ظاهر هم‌وزن.' if near >= 0.85 else 'یکنواختی وزنی کم است.'))
    else:
        weight = 'نامشخص'

    findings = []
    total = max(1, len(beits))
    for n, b in enumerate(beits, 1):
        for det in DETECTORS:
            findings.extend(det(b, ctx))
        if progress:
            progress(15 + int(70 * n / total), f'تحلیل بیت {fa(n)} از {fa(total)}')
    findings.extend(rhyme_findings(beits, rad, q1, q2, core))

    # تضمین نقلِ عینِ متن است، نه اشاره؛ اگر همان عبارت تلمیح هم شمرده شده باشد،
    # تلمیح کنار می‌رود تا یک نکته دو بار با دو نام گزارش نشود.
    tz_spans = {}
    for f in findings:
        if f.device == 'تضمین':
            tz_spans.setdefault(f.beit, []).append(set(W(f.evidence)))
    if tz_spans:
        findings = [f for f in findings
                    if not (f.device == 'تلمیح'
                            and set(W(f.evidence.split(' … ')[0]))
                            and any(set(W(f.evidence.split(' … ')[0])) <= sp
                                    for sp in tz_spans.get(f.beit, ())))]

    tick(88, 'جمع‌بندی و فیلتر دقت…')

    seen, uniq = set(), []
    for f in findings:
        k = (f.beit, f.device, f.kind, f.evidence)
        if k not in seen:
            seen.add(k)
            uniq.append(f)
    # یک نکته با دو شاهدِ هم‌پوشان دو بار گزارش نشود.
    compact = []
    for f in uniq:
        ev = set(W(f.evidence.replace(' … ', ' ')))
        dup = False
        for k, g in enumerate(compact):
            if (g.beit, g.device, g.mesra) != (f.beit, f.device, f.mesra):
                continue
            gv = set(W(g.evidence.replace(' … ', ' ')))
            if ev and gv and (ev <= gv or gv <= ev):
                if len(ev) > len(gv):
                    compact[k] = f
                dup = True
                break
        if not dup:
            compact.append(f)
    uniq = compact

    by_i = {b.i: b for b in beits}
    for f in uniq:
        apply_filter(f, by_i[f.beit])
    uniq.sort(key=lambda f: (f.beit, GROUP_ORDER.index(f.group), f.mesra, f.device))

    cnt = Counter(w for b in beits for w in b.tokens if w not in STOP and len(w) >= 3)
    keywords = [w for w, c in cnt.most_common(10) if c >= 1][:8]
    fam_counts = {}
    for name, fam in FAMILIES.items():
        n = sum(1 for b in beits for w in b.tokens if w in fam)
        if n:
            fam_counts[name] = n
    poly = []
    for b in beits:
        for w in dict.fromkeys(b.tokens):
            if w in HOMON:
                poly.append((b.i, w, ' / '.join(m for m, _ in HOMON[w])))

    return Result(beits, uniq, form, reasons, weight, syl, rad, q2, core, keywords, fam_counts, poly)


