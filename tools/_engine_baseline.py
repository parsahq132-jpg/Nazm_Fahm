def txt_step7(res):
    acc = accepted(res)
    L = ['مرحلهٔ ۷ — گزارش نهایی', '═' * 40, '']
    L.append('۱) معرفی شعر')
    L.append(f'  تعداد ابیات: {fa(len(res.beits))}   |   قالب: {res.form}   |   وزن: {res.weight}')
    if res.keywords:
        L.append(f'  موضوع/واژه‌های کلیدی: {" ، ".join(res.keywords)}')
    L += ['', '۲) جدول آرایه‌ها:']
    for r in table_rows(res):
        L.append(f'  بیت {r[0]} / مصراع {r[1]} / {r[2]} / «{r[3]}» / {r[4]}')
    L += ['', '۳) آرایه‌های شاخص']
    pick, used = [], set()
    cands = sorted(acc, key=lambda f: (f.status != 'تأیید',
                                       PRIORITY.index(f.device) if f.device in PRIORITY else 99))
    for f in cands:
        if f.device in PRIORITY and f.device not in used:
            used.add(f.device)
            pick.append(f)
        if len(pick) == 3:
            break
    if not pick:
        L.append('  آرایهٔ شاخصی پیدا نشد.')
    for f in pick:
        st = six_steps(f)
        L += [f'  ◆ {f.name} — بیت {fa(f.beit)}: «{f.evidence}»',
              f'     تعریف: {DEFS[f.device]}',
              f'     تطبیق: {f.note}',
              f'     گام ۶: {st["s6"]}']
    L += ['', '۴) نتیجه‌گیری']
    c = Counter(f.group for f in acc)
    if acc:
        L.append('  شمار آرایه‌ها: ' + ' ، '.join(f'{g} {fa(c[g])}' for g in GROUP_ORDER if c[g]))
        top = Counter(f.device for f in acc if META[f.device][0] != 'وزنی و قافیه‌ای').most_common(3)
        if top:
            L.append('  پربسامدترین: ' + ' ، '.join(f'{d} ({fa(n)})' for d, n in top))
    L.append('  مواردِ «با احتیاط» را با شرح‌های معتبر بسنجید.')
    return '\n'.join(L)


