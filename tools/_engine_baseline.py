# ── تضمین: نقلِ عینِ عبارت از شاعر دیگر یا آیه و حدیث ──
#  قاعده: هم‌واژگی واژه‌های پرتکرار هرگز تضمین نیست. باید رشته‌ای از دست‌کم
#  چهار واژهٔ پیوسته، عیناً و به همان ترتیب، از متنی شناخته‌شده در بیت آمده باشد.
#  برای اعلام قطعی، یا نشانگر انتساب («به قول»، نام شاعر، «مصرع»، «آیه»، …) در
#  بیت هست، یا نقل دست‌کم نیمی از مصراع را پر می‌کند. نقل کوتاهِ درونِ مصراعی
#  بلند، به‌تنهایی اعلام نمی‌شود.
#  فقط نشانگرهای نسبتاً ویژه؛ «به» و «گفت» و «بیت» به‌تنهایی در هر بیتی هست
#  و اگر نشانگر شمرده شوند، هر شعرِ اصلی هم «تضمین» می‌شود.
TAZMIN_MARKS = W("قول گفته فرموده گفتا میگوید میگویند مصرع نقل تضمین مضمون "
                 "دیوان روایت خواندم شنیدم")
_POET_NAMES = W("حافظ سعدی فردوسی مولانا مولوی نظامی خیام عطار جامی سنایی رودکی "
                "نیما شاملو اخوان سهراب شهریار پروین")
_TAZMIN_INDEX = None


def _tazmin_index():
    """نخستین حرفِ متنِ هر نقل → فهرست نقل‌ها (رشته، توکن‌های متن، شاعر، اثر).

    تطبیق روی رشتهٔ بی‌فاصله انجام می‌شود تا «آدم‌ها» و «آدمها» یکی شمرده شوند
    و مرز واژه‌ها هم بررسی شود (تطبیق نباید میان دو واژه بیفتد).
    """
    global _TAZMIN_INDEX
    if _TAZMIN_INDEX is not None:
        return _TAZMIN_INDEX
    idx = {}
    for toks, poet, work, raw in TAZMIN:
        j = ''.join(toks)
        if len(j) < 8:
            continue
        idx.setdefault(j[0], []).append((j, toks, poet, work))
    for v in idx.values():
        v.sort(key=lambda x: -len(x[0]))
    _TAZMIN_INDEX = idx
    return idx


def d_tazmin(b, ctx):
    """تضمین = بازتولیدِ عینِ دست‌کم چهار واژهٔ پیوسته از متنی شناخته‌شده."""
    idx = _tazmin_index()
    if not idx:
        return []
    out = []
    beit_tokens = set(b.tokens)
    # نشانگر انتساب، اطمینان را بالا می‌برد؛ ولی خودِ تطابق لفظی شاهد اصلی است.
    attr = bool(beit_tokens & TAZMIN_MARKS) or bool(beit_tokens & _POET_NAMES)
    matches = []
    for mnum, toks in ((M1, b.t1), (M2, b.t2)):
        if len(toks) < 3:
            continue
        joined, ends = '', [0]
        for t in toks:
            joined += t
            ends.append(len(joined))
        end_pos = {p: i for i, p in enumerate(ends)}
        used = []
        for pos in ends[:-1]:
            for qj, qtoks, poet, work in idx.get(joined[pos], ()):
                end = pos + len(qj)
                if end > len(joined) or joined[pos:end] != qj:
                    continue
                if end not in end_pos:      # نقل باید در مرز واژه تمام شود
                    continue
                if any(pos < e and s < end for s, e in used):
                    continue
                coverage = len(qj) / len(joined)
                if not attr and coverage < 0.35:
                    continue
                # اگر تمام مصراع عیناً همان مصراعِ منبع باشد و هیچ نشانگر انتسابی
                # نباشد، احتمال قوی‌تر این است که خودِ شعرِ اصلی باشد؛ سکوت می‌کنیم.
                if not attr and coverage >= 0.95:
                    continue
                i, k = end_pos[pos], end_pos[end] - end_pos[pos]
                used.append((pos, end))
                matches.append((mnum, ' '.join(toks[i:i + k]), poet, work,
                                'قوی' if (attr or coverage >= 0.75) else 'متوسط',
                                'نشانگر انتساب در بیت دیده شد' if attr else
                                f'نقل {fa(round(coverage * 100))}٪ از مصراع را پر کرده است'))

    # اگر هر دو مصراع از یک شاعر و یک اثر باشند و هیچ نشانگر انتسابی نباشد،
    # به احتمال زیاد خودِ شعرِ اصلی است، نه نقلِ آن در شعرِ دیگری.
    if not attr and len(matches) >= 2 and len({(m[2], m[3]) for m in matches}) == 1:
        return []

    for mnum, phrase, poet, work, conf, why in matches:
        out.append(mk(
            b, mnum, 'تضمین', 'عینِ متن', phrase,
            f'این عبارت عیناً از {poet} ({work}) گرفته شده است؛ {why}.',
            conf))
    return out


