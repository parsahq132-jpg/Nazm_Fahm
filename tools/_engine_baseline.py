def d_ihaam(b, ctx):
    out = []
    for w in dict.fromkeys(b.tokens):
        if w not in HOMON:
            continue
        hits = []
        for label, cw in HOMON[w]:
            h = [t for t in dict.fromkeys(b.tokens) if t in cw and t != w]
            if h:
                hits.append((label, h))
        mes = mesra_of(b, w)
        if len(hits) >= 2:
            ev = ' … '.join([w] + [hits[0][1][0], hits[1][1][0]])
            out.append(mk(b, mes, 'ایهام', '', ev,
                          f'«{w}» هم «{hits[0][0]}» و هم «{hits[1][0]}» می‌تواند باشد.', 'قوی'))
        elif len(hits) == 1:
            out.append(mk(b, mes, 'ایهام', 'تناسب (احتمالی)', ' … '.join([w, hits[0][1][0]]),
                          f'«{w}» چندمعنایی است و «{hits[0][1][0]}» با معنای «{hits[0][0]}» تناسب دارد.',
                          'ضعیف', True, 'ممکن است فقط یک معنا مراد باشد.'))
        else:
            out.append(mk(b, mes, 'ایهام', '', w, f'«{w}» چندمعنایی است.', 'ضعیف', False,
                          bad='برای معنای دوم قرینه‌ای نیست.'))
    return out
