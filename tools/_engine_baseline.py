_SEP = re.compile(r'\t+|\s{3,}|\s*[|…]+\s*|\s+[-–—]{2,}\s+|\s*\*\*\*\s*')


def parse_poem(text):
    lines = [l.strip() for l in text.replace('\r', '').split('\n') if l.strip()]
    mesras = []
    for l in lines:
        parts = [p.strip() for p in _SEP.split(l) if p.strip()]
        mesras.extend(parts if len(parts) >= 2 else [l])
    beits = []
    for k in range(0, len(mesras), 2):
        r1 = mesras[k]
        r2 = mesras[k + 1] if k + 1 < len(mesras) else ''
        b = Beit(len(beits) + 1, r1, r2)
        b.n1, b.n2 = normalize(r1), normalize(r2)
        b.t1, b.t2 = WORD_RE.findall(b.n1), WORD_RE.findall(b.n2)
        beits.append(b)
    return beits


