        def mousePressEvent(self, ev):
            if ev.button() == Qt.MouseButton.LeftButton and ev.position().y() < 60:
                self._drag_pos = ev.globalPosition().toPoint() - self.frameGeometry().topLeft()
                ev.accept()

        def mouseMoveEvent(self, ev):
            if self._drag_pos is not None and ev.buttons() & Qt.MouseButton.LeftButton:
                self.move(ev.globalPosition().toPoint() - self._drag_pos)
                ev.accept()

        def mouseReleaseEvent(self, ev):
            self._drag_pos = None

        def sample_menu(self):
            btn = self.sender()
            menu = QMenu(self)
            for label, text in SAMPLES.items():
                if not text:
                    menu.addSeparator()
                    sep = menu.addAction(label)
                    sep.setEnabled(False)
                    continue
                act = menu.addAction(label)
                act.triggered.connect(lambda checked=False, t=text: self.inp.setPlainText(t))
            menu.exec(btn.mapToGlobal(btn.rect().bottomLeft()))

        def fill(self, tb, rows, widths):
            tb.setRowCount(len(rows))
            for r, row in enumerate(rows):
                for c, v in enumerate(row):
                    item = QTableWidgetItem(str(v))
                    item.setTextAlignment(Qt.AlignmentFlag.AlignRight | Qt.AlignmentFlag.AlignVCenter)
                    tb.setItem(r, c, item)
            for c, w in enumerate(widths):
                tb.setColumnWidth(c, w)
            tb.resizeRowsToContents()

        def run(self):
            text = self.inp.toPlainText().strip()
            if not text:
                QMessageBox.information(self, 'توجه', 'اول متن شعر یا جمله را وارد کنید.')
                return
            if getattr(self, 'worker', None) is not None and self.worker.isRunning():
                return
            self.analyze_btn.setEnabled(False)
            self.prog.setValue(0)
            self.prog.setFormat('در حال آماده‌سازی… %p٪')
            self.worker = AnalyzeWorker(text, self)
            self.worker.progressed.connect(self.on_progress)
            self.worker.finished_ok.connect(self.on_done)
            self.worker.failed.connect(self.on_failed)
            self.worker.start()

        def on_progress(self, p, msg):
            self.prog.setValue(max(0, min(100, int(p))))
            self.prog.setFormat(f'{msg} — %p٪')

        def on_failed(self, msg):
            self.prog.setValue(0)
            self.prog.setFormat('خطا در تحلیل')
            self.analyze_btn.setEnabled(True)
            QMessageBox.warning(self, 'خطا', f'تحلیل انجام نشد:\n{msg}')

        def on_done(self, res):
            self.res = res
            self.prog.setValue(100)
            self.prog.setFormat('تحلیل کامل شد — ۱۰۰٪')
            self.analyze_btn.setEnabled(True)
            self.render_result(res)

