_DIAC = re.compile('[\u064B-\u065F\u0670\u0640\u200e\u200f]')
WORD_RE = re.compile(r'[\u0621-\u063A\u0641-\u064A\u067E\u0686\u0698\u06A9\u06AF\u06CC]+')
_FA_DIGITS = str.maketrans('0123456789', '۰۱۲۳۴۵۶۷۸۹')


def fa(x):
    return str(x).translate(_FA_DIGITS)


def normalize(s):
    # یکسان‌سازی حروف عربی/فارسی + نیم‌فاصله + نشانه‌های جهت
    for a, b in (('ي', 'ی'), ('ك', 'ک'), ('ە', 'ه'), ('ۀ', 'ه'), ('ة', 'ه'),
                 ('أ', 'ا'), ('إ', 'ا'), ('ٱ', 'ا'), ('ؤ', 'و'), ('ئ', 'ی'),
                 ('ﻻ', 'لا'), ('ى', 'ی')):
        s = s.replace(a, b)
    s = _DIAC.sub('', s)
    s = s.replace('\u200f', '').replace('\u200e', '')
    return s.replace('\u200c', ' ').replace('\u00a0', ' ')


def W(s):
    return set(normalize(s).split())


def lev(a, b):
    if a == b:
        return 0
    if abs(len(a) - len(b)) > 1:
        return 2
    prev = list(range(len(b) + 1))
    for i, ca in enumerate(a, 1):
        cur = [i]
        for j, cb in enumerate(b, 1):
            cur.append(min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + (ca != cb)))
        prev = cur
    return prev[-1]


def syl_count(w):
    seq, n = [], len(w)
    for i, ch in enumerate(w):
        prev = w[i - 1] if i > 0 else ''
        nxt = w[i + 1] if i + 1 < n else ''
        if ch == 'آ':
            seq += ['C', 'V']
        elif ch == 'ا':
            seq.append('C' if i == 0 else 'V')
        elif ch in 'یو':
            if i == 0:
                seq.append('C')
            elif ch == 'و' and prev == 'خ' and nxt in ('ا', 'آ'):
                continue
            elif nxt in ('ا', 'آ'):
                seq.append('C')
            else:
                seq.append('V')
        elif ch == 'ه' and i == n - 1 and n >= 2 and seq and seq[-1] == 'C':
            seq.append('V')
        else:
            seq.append('C')
    v = seq.count('V')
    if v == 0:
        return 1
    lead = 0
    for s in seq:
        if s == 'C':
            lead += 1
        else:
            break
    return v + (1 if lead >= 2 else 0)


def rkey(w):
    if not w:
        return ''
    return 'ا' if w.endswith('ا') else w[-2:]


def ends_rhyme(a, b):
    return bool(a) and bool(b) and rkey(a) == rkey(b)


def common_suffix(words):
    if not words:
        return ''
    s = words[0]
    for w in words[1:]:
        k = 0
        while k < min(len(s), len(w)) and s[-1 - k] == w[-1 - k]:
            k += 1
        s = s[len(s) - k:] if k else ''
    return s


def stem(w):
    for suf in ('هایی', 'های', 'ها', 'ان', 'ات', 'ی'):
        if w.endswith(suf) and len(w) - len(suf) >= 3:
            return w[:-len(suf)]
    return w


