def d_takrir_jenas_tam(b, ctx):
    out = []
    cnt = Counter()
    for toks in (b.t1, b.t2):
        for i, w in enumerate(toks):
            if w in STOP or len(w) < 2:
                continue
            if i and toks[i - 1] in ('می', 'نمی'):
                continue        # پارهٔ فعل، نه تکرار واژه
            cnt[w] += 1
    for w, c in cnt.items():
        if c < 2:
            continue
        mes = M12 if (w in b.t1 and w in b.t2) else (M1 if w in b.t1 else M2)
        ev = f'{w} … {w}'
        if w in HOMON:
            out.append(mk(b, mes, 'جناس', 'تام', ev,
                          f'واژهٔ «{w}» دو بار آمده و چندمعنایی است.'))
            continue
        alt = ''
        if b.t1 and b.t2 and b.t1[-1] == w and b.t2[-1] == w:
            alt = 'تکرار در پایان هر دو مصراع ممکن است ردیف باشد.'
        elif w in ctx['radif']:
            alt = 'این واژه جزو ردیف است.'
        out.append(mk(b, mes, 'تکرار', '', ev,
                      f'واژهٔ «{w}» {fa(c)} بار تکرار شده است.', 'متوسط', True, alt))
    return out


_RARE = set('سشزژخفقصثغچجحطظضع')
_COMMON = set('رندتم')
_VOWELS = set('اآویه')


def d_vaj(b, ctx):
    out = []
    for mnum, toks, c in ((M1, b.t1, b.c1), (M2, b.t2, b.c2)):
        letters = [ch for ch in c if ch != ' ' and ch not in _VOWELS]
        if len(letters) < 8:
            continue
        best = None
        for ch, n in Counter(letters).items():
            thr = 4 if ch in _RARE else (6 if ch in _COMMON else 5)
            spread = sum(1 for t in toks if ch in t)
            if n >= thr and spread >= 3 and (best is None or n - thr > best[1] - best[2]):
                best = (ch, n, thr)
        if best:
            ch, n, thr = best
            out.append(mk(b, mnum, 'واج‌آرایی', '', c,
                          f'حرف «{ch}» {fa(n)} بار در این مصراع آمده است.',
                          'متوسط' if n > thr else 'ضعیف'))
    return out


_INFL = ('ها', 'ان', 'ی', 'را', 'م', 'ت', 'ش', 'ید', 'ند', 'یم', 'تر', 'ین', 'ای')


def d_jenas(b, ctx):
    out = []
    words = [w for w in dict.fromkeys(b.tokens) if w not in STOP and len(w) >= 3]
    for x in range(len(words)):
        for y in range(x + 1, len(words)):
            a, c = words[x], words[y]
            s, l = (a, c) if len(a) <= len(c) else (c, a)
            d = lev(a, c)
            kind = None
            if d == 1:
                if l.startswith(s) and l[len(s):] in _INFL:
                    continue
                if len(a) == len(c):
                    kind = 'ناقص — اختلاف در یک حرف'
                else:
                    kind = 'زاید — یک حرف اضافه'
            elif len(a) == len(c) and len(a) >= 4 and sorted(a) == sorted(c):
                kind = 'قلب — جابه‌جایی حروف'
            if kind:
                m = min(len(a), len(c))
                if m < 4:
                    continue
                conf = 'متوسط' if m == 4 else 'قوی'
                out.append(mk(b, mesra_of(b, a, c), 'جناس', kind, f'{a} … {c}',
                              f'«{a}» و «{c}» از نظر شکل و آوا نزدیک‌اند.', conf))
    return out


_PUNCT = re.compile(r'[،؛,;:؟!.\-–—]+')


def d_saj(b, ctx):
    out = []
    for mnum, n in ((M1, b.n1), (M2, b.n2)):
        segs = [WORD_RE.findall(s) for s in _PUNCT.split(n)]
        segs = [s for s in segs if s]
        if len(segs) < 2:
            continue
        for x in range(len(segs) - 1):
            a, c = segs[x][-1], segs[x + 1][-1]
            # پسوند دوحرفی معمولاً فقط شناسهٔ فعل است («نباشند/مانند») و سجع نیست.
            if a != c and len(a) >= 3 and len(c) >= 3 and len(common_suffix([a, c])) >= 3:
                kind = 'موازنه' if (len(segs[x]) == len(segs[x + 1]) >= 3) else 'سجع'
                out.append(mk(b, mnum, 'موازنه' if kind == 'موازنه' else 'سجع', '',
                              f'{a} … {c}',
                              f'پایان دو بخش مصراع («{a}» و «{c}») هم‌آهنگ است.', 'متوسط'))
    return out


def d_tashbih(b, ctx):
    out = []
    for mnum, toks, c in ((M1, b.t1, b.c1), (M2, b.t2, b.c2)):
        for i, w in enumerate(toks):
            if w not in ADAT:
                continue
            # «نمی‌مانند» پس از نرمال‌سازی به «نمی مانند» می‌شکند؛ «مانند»ِ
            # چسبیده به «می/نمی» جزء فعل است، نه ادات تشبیه.
            if i and toks[i - 1] in ('می', 'نمی') and w not in STRONG_ADAT:
                continue
            li = i - 1
            if w == 'سان' and li >= 0 and toks[li] in ('به', 'بر'):
                li -= 1
            left = toks[li] if li >= 0 else ''
            right = toks[i + 1] if i + 1 < len(toks) else ''
            if not left or not right or left in STOP or right in STOP:
                continue
            if i + 2 < len(toks) and toks[i + 1] in ('بر', 'در', 'با', 'از'):
                continue
            img = right in IMAGES
            sub = left in SUBJECTS
            wajh = next((t for t in toks[i + 2:i + 4] if t in WAJH), '')
            kind = 'مرسل مفصّل' if wajh else 'مرسل مجمل'
            ev = ' '.join(toks[li:i + 2] + ([wajh] if wajh else []))
            if ev not in c:
                ev = f'{left} … {w} … {right}'
            note = (f'مشبه: {left} | ادات: {w} | مشبه‌به: {right}' +
                    (f' | وجه شبه: {wajh}' if wajh else ' | وجه شبه: حذف‌شده'))
            if (img and sub) or (img or sub):
                out.append(mk(b, mnum, 'تشبیه', kind, ev, note,
                              'قوی' if (img and sub) else 'متوسط'))
            elif w in STRONG_ADAT:
                out.append(mk(b, mnum, 'تشبیه', kind, ev, note, 'ضعیف'))
        for i in range(len(toks) - 1):
            a, c2 = toks[i], toks[i + 1]
            if a in SUBJECTS and c2 in IMAGES and c2 not in ABSTRACT:
                if i + 2 < len(toks) and toks[i + 2] in ('است', 'بود', 'شد', 'گشت', 'نیست', 'باشد'):
                    out.append(mk(b, mnum, 'تشبیه', 'بلیغ اضافی', f'{a} {c2}',
                                  f'«{a}» به «{c2}» مانند شده بدون ادات.', 'متوسط'))
            elif a in IMAGES and c2 in ABSTRACT:
                out.append(mk(b, mnum, 'تشبیه', 'بلیغ اضافهٔ تشبیهی', f'{a} {c2}',
                              f'«{c2}» به «{a}» مانند شده (مثل «دریای غم»).', 'متوسط'))
        for i, w in enumerate(toks[:-1]):
            if w == 'ای' and toks[i + 1] in IMAGES:
                x = toks[i + 1]
                out.append(mk(b, mnum, 'استعاره', 'مصرّحه', f'ای {x}',
                              f'«{x}» در خطاب، به‌جای شخص نشسته است.', 'متوسط', True,
                              '' if x in BELOVED_IMG else
                              'اگر خود آن شیء مورد خطاب باشد، تشخیص است.'))
    return out


def d_tashkhis_majaz(b, ctx):
    out = []
    for mnum, toks in ((M1, b.t1), (M2, b.t2)):
        for j, v in enumerate(toks):
            if not HUMAN_VERB.match(v) or v in _MODAL_V:
                continue
            prev = toks[:j]
            nxt = toks[j + 1:] if j + 1 < len(toks) else []
            nat = next((t for t in reversed(prev) if t in NATURE), '')
            cos = next((t for t in reversed(prev) if t in COSMIC), '')
            abst = next((t for t in reversed(prev) if t in ABSTRACT), '')
            img = next((t for t in reversed(prev) if t in IMAGES), '')
            ves = next((t for t in reversed(prev) if t in VESSEL), '')
            place = next((t for t in reversed(prev) if t in PLACES), '')
            subj = next((t for t in reversed(prev) if t in SUBJECTS), '')

            if ves and v in DRINK_V:
                out.append(mk(b, mnum, 'مجاز', 'علاقهٔ ظرف به مظروف',
                              f'{ves} … {v}',
                              f'«{ves}» (ظرف) به‌جای محتوای آن آمده است.', 'قوی'))
                continue

            if img and img not in NATURE and img not in ABSTRACT and img not in COSMIC:
                continue

            target = nat or cos or abst
            if not target:
                nat2 = next((t for t in nxt if t in NATURE), '')
                cos2 = next((t for t in nxt if t in COSMIC), '')
                abst2 = next((t for t in nxt if t in ABSTRACT), '')
                target = nat2 or cos2 or abst2
            human = next((t for t in prev if t in HUMAN_SUBJ
                          and t not in NATURE and t not in COSMIC), '')
            # فعل عمومی بدون فاعل انسانی، شاهد شخصی‌بخشی نیست.
            if v in _GENERIC_HUMAN_V and not human:
                continue
            if target:
                if target in IMAGES and target not in NATURE and target not in COSMIC and target not in ABSTRACT:
                    continue
                alt = f'در مصراع «{human}» هم آمده.' if human else ''
                out.append(mk(b, mnum, 'تشخیص', 'استعارهٔ مکنیه',
                              f'{target} … {v}',
                              f'«{target}» کاری انسانی («{v}») کرده است.',
                              'قوی' if not human else 'ضعیف', True, alt))
            elif subj:
                out.append(mk(b, mnum, 'تشخیص', 'استعارهٔ مکنیه (احتمالی)',
                              f'{subj} … {v}',
                              f'«{subj}» کاری انسانی («{v}») کرده است.',
                              'ضعیف', True,
                              'احتمال مجاز/کنایه هم هست.'))
            elif place and not human:
                out.append(mk(b, mnum, 'مجاز', 'علاقهٔ محلیه',
                              f'{place} … {v}',
                              f'«{place}» به‌جای مردم آن آمده است.', 'متوسط'))
    return out


