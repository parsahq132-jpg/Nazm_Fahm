def d_kenaye(b, ctx):
    out = []
    for mnum, c in ((M1, b.c1), (M2, b.c2)):
        all_matches = []
        for pat, meaning in IDIOMS:
            try:
                for m in re.finditer(pat, c):
                    all_matches.append((m.group(0), meaning, m.start(), m.end()))
            except re.error:
                continue
        for pat, meaning in _STRUCT_KENAYE:
            for m in pat.finditer(c):
                all_matches.append((m.group(0), meaning, m.start(), m.end()))
        filtered = []
        for ev, meaning, start, end in all_matches:
            is_sub = any(ev != ev2 and ev in ev2 and start >= start2 and end <= end2
                         for ev2, _, start2, end2 in all_matches)
            if not is_sub and not any(ev == f[0] for f in filtered):
                filtered.append((ev, meaning))
        for ev, meaning in filtered:
            out.append(mk(b, mnum, 'کنایه', '', ev, f'معنای مراد: {meaning}', 'قوی'))
    return out


